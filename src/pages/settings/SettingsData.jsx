import React, { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { AlertTriangle, Download, Loader2 } from 'lucide-react';
import { base44 } from '@/api/base44Client';
import { Button } from '@/components/ui/button';
import { SettingsCard } from '@/components/settings/SettingsUI';
import {
  AlertDialog,
  AlertDialogAction,
  AlertDialogCancel,
  AlertDialogContent,
  AlertDialogDescription,
  AlertDialogFooter,
  AlertDialogHeader,
  AlertDialogTitle,
  AlertDialogTrigger,
} from '@/components/ui/alert-dialog';

const OWNED = [
  ['projects', 'Project'],
  ['pages', 'StudioPage'],
  ['messages', 'StudioMessage'],
  ['tasks', 'StudioTask'],
  ['agents', 'StudioAgent'],
  ['automations', 'Automation'],
  ['notifications', 'Notification'],
  ['releases', 'Deployment'],
  ['qa', 'QaRun'],
];

export default function SettingsData() {
  const navigate = useNavigate();
  const [busy, setBusy] = useState('');
  const [notice, setNotice] = useState('');

  const exportAll = async () => {
    setBusy('export');
    setNotice('');
    const me = await base44.auth.me();
    const entries = await Promise.all(
      OWNED.map(async ([key, entity]) => {
        const page = await base44.entities[entity].filter({ created_by_id: me.id }, { limit: 300 });
        return [key, page.items];
      })
    );
    const payload = {
      exported_at: new Date().toISOString(),
      account: { id: me.id, email: me.email, full_name: me.full_name },
      data: Object.fromEntries(entries),
    };
    const blob = new Blob([JSON.stringify(payload, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `x1-apex-factory-export-${new Date().toISOString().slice(0, 10)}.json`;
    link.click();
    URL.revokeObjectURL(url);
    setNotice('Export downloaded.');
    setBusy('');
  };

  const deleteAll = async () => {
    setBusy('delete');
    const me = await base44.auth.me();
    for (const [, entity] of OWNED) {
      await base44.entities[entity].deleteMany({ created_by_id: me.id });
    }
    setBusy('');
    navigate('/');
  };

  return (
    <>
      <SettingsCard
        title="Export your studio"
        description="Downloads every session, project, agent, automation and release you own as JSON."
        footer={
          <Button size="sm" variant="outline" className="gap-1.5" onClick={exportAll} disabled={busy === 'export'}>
            {busy === 'export' ? <Loader2 size={12} className="animate-spin" /> : <Download size={12} />}
            Export JSON
          </Button>
        }
      >
        <p className="text-[11.5px] leading-relaxed text-muted-foreground">
          Files generated by sessions stay in artifact storage and are not part of this archive.
        </p>
        {notice && <p className="mt-2 text-[11px] text-emerald-600">{notice}</p>}
      </SettingsCard>

      <SettingsCard title="Delete studio data" description="Irreversible. Removes everything you own in this workspace.">
        <div className="flex items-start gap-2 rounded-lg border border-destructive/30 bg-destructive/5 px-3 py-2.5">
          <AlertTriangle size={14} className="mt-0.5 shrink-0 text-destructive" />
          <p className="text-[11px] leading-relaxed text-muted-foreground">
            Your account stays active, but sessions, projects, agents, automations, notifications and releases are
            permanently removed. Export first if you need a copy.
          </p>
        </div>

        <AlertDialog>
          <AlertDialogTrigger asChild>
            <Button size="sm" variant="destructive" className="mt-3" disabled={busy === 'delete'}>
              {busy === 'delete' && <Loader2 size={12} className="animate-spin" />}
              Delete all studio data
            </Button>
          </AlertDialogTrigger>
          <AlertDialogContent>
            <AlertDialogHeader>
              <AlertDialogTitle>Delete all studio data?</AlertDialogTitle>
              <AlertDialogDescription>
                This removes every session, project, agent, automation and release you own. It cannot be undone.
              </AlertDialogDescription>
            </AlertDialogHeader>
            <AlertDialogFooter>
              <AlertDialogCancel>Keep my data</AlertDialogCancel>
              <AlertDialogAction onClick={deleteAll}>Delete everything</AlertDialogAction>
            </AlertDialogFooter>
          </AlertDialogContent>
        </AlertDialog>
      </SettingsCard>
    </>
  );
}